DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='TB_BANGLUONG' AND COLUMN_NAME='CONG_INPUT_REV_AT_CALC';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE HR.TB_BANGLUONG ADD (CONG_INPUT_REV_AT_CALC NUMBER)'; END IF;
 SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='TB_BANGLUONG' AND COLUMN_NAME='CONG_PUBLISH_REV_AT_CALC';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE HR.TB_BANGLUONG ADD (CONG_PUBLISH_REV_AT_CALC NUMBER)'; END IF;
END;
/
MERGE INTO HR.TB_SYS_FUNCTION t USING (
 SELECT TO_NCHAR('F_CC_CONGBO_LUONG') FUNCTION_CODE,TO_NCHAR('Công bố lương') DESCRIPTION,
 PARENT, SORT+1 SORT FROM HR.TB_SYS_FUNCTION WHERE FUNCTION_CODE='F_CC_BANGLUONG'
) s ON (t.FUNCTION_CODE=s.FUNCTION_CODE)
WHEN NOT MATCHED THEN INSERT (FUNCTION_CODE,DESCRIPTION,PARENT,SORT,ISGROUP,MENU,TIPS,RIGHT_TYPE)
 VALUES(s.FUNCTION_CODE,s.DESCRIPTION,s.PARENT,s.SORT,0,0,TO_NCHAR('Quyền Sửa cho phép công bố; sau công bố khóa bất biến lương và bảng công.'),'FUNCTION');
COMMIT;
