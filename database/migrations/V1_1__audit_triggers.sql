-- 1. BẢNG LƯU TRỮ NHẬT KÝ KIỂM TOÁN (AUDIT TRAIL)
CREATE TABLE TB_AUDIT_LOG (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TABLE_NAME VARCHAR2(100) NOT NULL,
    ACTION_TYPE VARCHAR2(20) NOT NULL, -- INSERT, UPDATE, DELETE
    RECORD_ID VARCHAR2(100),
    OLD_VALUES CLOB,
    NEW_VALUES CLOB,
    PERFORMED_BY NUMBER,
    PERFORMED_BY_USERNAME VARCHAR2(100),
    PERFORMED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CLIENT_IP VARCHAR2(50),
    CONSTRAINT PK_TB_AUDIT_LOG PRIMARY KEY (ID)
);

-- Index tra cứu vết kiểm toán theo bảng và ngày thao tác
CREATE INDEX IX_AUDIT_TABLE_DATE ON TB_AUDIT_LOG (TABLE_NAME, PERFORMED_AT);
CREATE INDEX IX_AUDIT_USER ON TB_AUDIT_LOG (PERFORMED_BY);

-- 2. TRIGGER KIỂM TOÁN NHÂN SỰ
CREATE OR REPLACE TRIGGER TRG_AUDIT_NHANVIEN
AFTER INSERT OR UPDATE OR DELETE ON TB_NHANVIEN
FOR EACH ROW
DECLARE
    v_action VARCHAR2(20);
    v_rec_id VARCHAR2(100);
BEGIN
    IF INSERTING THEN
        v_action := 'INSERT';
        v_rec_id := TO_CHAR(:NEW.MANV);
        INSERT INTO TB_AUDIT_LOG (TABLE_NAME, ACTION_TYPE, RECORD_ID, NEW_VALUES, PERFORMED_BY)
        VALUES ('TB_NHANVIEN', v_action, v_rec_id, 'Họ tên: ' || :NEW.HOTEN || ', PB: ' || :NEW.IDPB, :NEW.CREATED_BY);
    ELSIF UPDATING THEN
        v_action := 'UPDATE';
        v_rec_id := TO_CHAR(:NEW.MANV);
        INSERT INTO TB_AUDIT_LOG (TABLE_NAME, ACTION_TYPE, RECORD_ID, OLD_VALUES, NEW_VALUES, PERFORMED_BY)
        VALUES ('TB_NHANVIEN', v_action, v_rec_id, 'Cũ: ' || :OLD.HOTEN || ', PB: ' || :OLD.IDPB, 'Mới: ' || :NEW.HOTEN || ', PB: ' || :NEW.IDPB, :NEW.UPDATED_BY);
    ELSIF DELETING THEN
        v_action := 'DELETE';
        v_rec_id := TO_CHAR(:OLD.MANV);
        INSERT INTO TB_AUDIT_LOG (TABLE_NAME, ACTION_TYPE, RECORD_ID, OLD_VALUES, PERFORMED_BY)
        VALUES ('TB_NHANVIEN', v_action, v_rec_id, 'Đã xóa NV: ' || :OLD.HOTEN, :OLD.DELETED_BY);
    END IF;
END;
/

