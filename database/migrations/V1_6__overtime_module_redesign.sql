-- 1. BỔ SUNG CỘT CHO BẢNG TB_TANGCA
DECLARE
    v_col_count NUMBER;
    PROCEDURE add_col_if_not_exists(p_table VARCHAR2, p_col VARCHAR2, p_def VARCHAR2) IS
        v_cnt NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cnt FROM USER_TAB_COLUMNS 
        WHERE TABLE_NAME = UPPER(p_table) AND COLUMN_NAME = UPPER(p_col);
        IF v_cnt = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_col || ' ' || p_def || ')';
        END IF;
    END;
BEGIN
    add_col_if_not_exists('TB_TANGCA', 'GIOBATDAU', 'VARCHAR2(10)');
    add_col_if_not_exists('TB_TANGCA', 'GIOKETTHUC', 'VARCHAR2(10)');
    add_col_if_not_exists('TB_TANGCA', 'IDLOAICONG', 'NUMBER');
    add_col_if_not_exists('TB_TANGCA', 'HESOTC', 'FLOAT(126)');
    add_col_if_not_exists('TB_TANGCA', 'DONGIATC', 'FLOAT(126)');
    add_col_if_not_exists('TB_TANGCA', 'IS_THUVIEC', 'NUMBER(1) DEFAULT 0');
END;
/

-- 2. CẬP NHẬT DỮ LIỆU CŨ TRONG TB_TANGCA NẾU ĐANG TRỎ VÀO IDLOAICA = 3
UPDATE TB_TANGCA SET IDLOAICA = 1 WHERE IDLOAICA = 3;
COMMIT;

-- 3. CHUẨN HÓA TB_LOAICA: Ca ngày (1.00), Ca đêm (1.25)
MERGE INTO TB_LOAICA dst
USING (
    SELECT 1 AS IDLOAICA, N'Ca ngày' AS TENLOAICA, 1.00 AS HESOLOAICA FROM DUAL UNION ALL
    SELECT 2,             N'Ca đêm',                1.25 FROM DUAL
) src
ON (dst.IDLOAICA = src.IDLOAICA)
WHEN MATCHED THEN
    UPDATE SET dst.TENLOAICA = src.TENLOAICA, dst.HESOLOAICA = src.HESOLOAICA
WHEN NOT MATCHED THEN
    INSERT (IDLOAICA, TENLOAICA, HESOLOAICA, CREATED_DATE) VALUES (src.IDLOAICA, src.TENLOAICA, src.HESOLOAICA, SYSDATE);

DELETE FROM TB_LOAICA WHERE IDLOAICA NOT IN (1, 2);
COMMIT;

-- 4. CHUẨN HÓA TB_LOAICONG: Công ngày thường (1.00), Công Chủ nhật (1.50), Công ngày lễ (2.00)
MERGE INTO TB_LOAICONG dst
USING (
    SELECT 1 AS IDLOAICONG, N'Công ngày thường' AS TENLC, 1.00 AS HESOLOAICONG FROM DUAL UNION ALL
    SELECT 2,               N'Công Chủ nhật',             1.50 FROM DUAL UNION ALL
    SELECT 3,               N'Công ngày lễ',              2.00 FROM DUAL
) src
ON (dst.IDLOAICONG = src.IDLOAICONG)
WHEN MATCHED THEN
    UPDATE SET dst.TENLC = src.TENLC, dst.HESOLOAICONG = src.HESOLOAICONG
WHEN NOT MATCHED THEN
    INSERT (IDLOAICONG, TENLC, HESOLOAICONG, CREATED_DATE) VALUES (src.IDLOAICONG, src.TENLC, src.HESOLOAICONG, SYSDATE);

DELETE FROM TB_LOAICONG WHERE IDLOAICONG NOT IN (1, 2, 3);
COMMIT;

