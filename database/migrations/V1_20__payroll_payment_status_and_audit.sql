-- Migration V1_20: Separation of Payroll Locking (KHOA) and Payment Confirmation (CHI_TRA)
-- ACID & Audit Trail Enhancement for Period Closing and Disbursement
-- Note: Draft script - do NOT execute directly on live production without scheduled maintenance window.

BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'HR' THEN
        RAISE_APPLICATION_ERROR(-20000, 'HR schema required');
    END IF;
END;
/

-- 1. Add payment tracking columns to TB_KYCONG (Period Level)
ALTER TABLE TB_KYCONG ADD (
    TRANGTHAI_CHITRA VARCHAR2(30) DEFAULT 'CHUA_CHI_TRA' NOT NULL,
    NGAY_CHITRA TIMESTAMP NULL,
    NGUOI_CHITRA NUMBER(10) NULL,
    GHI_CHU_CHITRA NVARCHAR2(500) NULL
)
/

ALTER TABLE TB_KYCONG ADD CONSTRAINT CK20_KYCONG_CHITRA 
    CHECK (TRANGTHAI_CHITRA IN ('CHUA_CHI_TRA', 'DANG_CHI_TRA', 'DA_CHI_TRA', 'HUY_CHI_TRA'))
/

ALTER TABLE TB_KYCONG ADD CONSTRAINT FK20_KYCONG_NGUOI_CHITRA 
    FOREIGN KEY (NGUOI_CHITRA) REFERENCES TB_SYS_USER(IDUSER)
/

-- Business rule constraint: Payment cannot be confirmed unless the period is locked (KHOA = 1)
ALTER TABLE TB_KYCONG ADD CONSTRAINT CK20_PAYMENT_REQUIRES_LOCK 
    CHECK (TRANGTHAI_CHITRA <> 'DA_CHI_TRA' OR KHOA = 1)
/

-- 2. Add payment tracking columns to TB_BANGLUONG (Employee Level)
ALTER TABLE TB_BANGLUONG ADD (
    TRANGTHAI_CHITRA VARCHAR2(30) DEFAULT 'CHUA_CHI_TRA' NOT NULL,
    NGAY_CHITRA TIMESTAMP NULL,
    SO_LENH_CHI VARCHAR2(50) NULL,
    NGUON_CHI_TRA VARCHAR2(50) NULL,
    MA_GIAO_DICH_NH VARCHAR2(100) NULL,
    GHI_CHU_CHITRA NVARCHAR2(500) NULL
)
/

ALTER TABLE TB_BANGLUONG ADD CONSTRAINT CK20_BANGLUONG_CHITRA 
    CHECK (TRANGTHAI_CHITRA IN ('CHUA_CHI_TRA', 'DANG_CHI_TRA', 'DA_CHI_TRA', 'HUY_CHI_TRA', 'LOI_CHI_TRA'))
/

-- 3. Create Payment Confirmation History / Audit Log Table
CREATE TABLE TB_PAYROLL_PAYMENT_LOG (
    LOG_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    MAKYCONG NUMBER(10) NOT NULL REFERENCES TB_KYCONG(MAKYCONG),
    IDBL NUMBER(18) NULL REFERENCES TB_BANGLUONG(IDBL),
    MANV NUMBER(10) NULL REFERENCES TB_NHANVIEN(MANV),
    HANH_DONG VARCHAR2(50) NOT NULL,
    SO_TIEN_CHI NUMBER(18, 2) NOT NULL,
    PHUONG_THUC VARCHAR2(50) NOT NULL,
    TRANGTHAI_TRUOC VARCHAR2(30) NOT NULL,
    TRANGTHAI_SAU VARCHAR2(30) NOT NULL,
    THOI_DIEM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    THUC_HIEN_BOI NUMBER(10) NOT NULL REFERENCES TB_SYS_USER(IDUSER),
    GHI_CHU NVARCHAR2(1000) NULL
)
/

CREATE INDEX IX20_PAYLOG_MAKYCONG ON TB_PAYROLL_PAYMENT_LOG(MAKYCONG, THOI_DIEM)
/

COMMENT ON COLUMN TB_KYCONG.TRANGTHAI_CHITRA IS 'Trạng thái chi trả cấp kỳ công: CHUA_CHI_TRA, DANG_CHI_TRA, DA_CHI_TRA, HUY_CHI_TRA'
/
COMMENT ON COLUMN TB_KYCONG.KHOA IS 'Khóa sổ dữ liệu (1: Locked, 0: Open). Độc lập hoàn toàn với TRANGTHAI_CHITRA'
/
COMMENT ON TABLE TB_PAYROLL_PAYMENT_LOG IS 'Nhật ký kiểm toán giao dịch xác nhận chi trả lương'
/
