CREATE OR REPLACE PROCEDURE HRMS_ASSERT_PAYROLL_OPEN(p_period NUMBER) AS
 v_locked NUMBER;
BEGIN
 IF p_period IS NULL THEN RETURN; END IF;
 -- Serialize each writer with publication on the same period row.
 SELECT LUONG_CONGBO_LOCKED INTO v_locked FROM TB_KYCONG WHERE MAKYCONG=p_period FOR UPDATE;
 IF v_locked=1 THEN RAISE_APPLICATION_ERROR(-20044,'PAYROLL_FROZEN: published payroll and attendance are read-only.'); END IF;
EXCEPTION
 WHEN NO_DATA_FOUND THEN NULL;
 WHEN OTHERS THEN
  -- An unfrozen period DELETE can cascade to payroll. Its BEFORE ROW trigger
  -- has already rejected every frozen period; Oracle forbids querying that
  -- mutating parent during the cascade. No other error is ignored.
  IF SQLCODE<>-4091 THEN RAISE; END IF;
END;
/

CREATE OR REPLACE PROCEDURE HRMS_ASSERT_PAYROLL_SLIP(p_id NUMBER) AS
 p NUMBER;
BEGIN
 IF p_id IS NULL THEN RETURN; END IF;
 SELECT MAKYCONG INTO p FROM TB_BANGLUONG WHERE IDBL=p_id;
 HRMS_ASSERT_PAYROLL_OPEN(p);
END;
/

CREATE OR REPLACE PROCEDURE HRMS_ASSERT_PAYROLL_DATES(p_start DATE,p_end DATE) AS
BEGIN
 IF p_start IS NULL THEN RETURN; END IF;
 FOR r IN (SELECT MAKYCONG FROM TB_KYCONG
   WHERE MAKYCONG BETWEEN EXTRACT(YEAR FROM p_start)*100+EXTRACT(MONTH FROM p_start)
     AND EXTRACT(YEAR FROM NVL(p_end,p_start))*100+EXTRACT(MONTH FROM NVL(p_end,p_start)) ORDER BY MAKYCONG)
 LOOP HRMS_ASSERT_PAYROLL_OPEN(r.MAKYCONG); END LOOP;
END;
/

CREATE OR REPLACE TRIGGER TRG45_PERIOD_FROZEN
 BEFORE INSERT OR UPDATE OR DELETE ON TB_KYCONG FOR EACH ROW
BEGIN
 IF (UPDATING OR DELETING) AND :OLD.LUONG_CONGBO_LOCKED=1 THEN
  RAISE_APPLICATION_ERROR(-20044,'PAYROLL_FROZEN: published period cannot change or be reopened.');
 END IF;
 IF INSERTING AND :NEW.LUONG_CONGBO_LOCKED=1 THEN
  RAISE_APPLICATION_ERROR(-20044,'PAYROLL_FROZEN: publish through the payroll workflow.');
 END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG45_PAYROLL_FROZEN
 FOR INSERT OR UPDATE OR DELETE ON TB_BANGLUONG COMPOUND TRIGGER
 TYPE period_set IS TABLE OF BOOLEAN INDEX BY PLS_INTEGER;
 frozen_periods period_set;
 BEFORE EACH ROW IS
 BEGIN
  IF UPDATING OR DELETING THEN
   IF UPPER(TRIM(:OLD.TRANG_THAI)) IN ('PUBLISHED','APPROVED','CONG_BO','DA_DUYET','PAID','DA_CHI_TRA') THEN
    RAISE_APPLICATION_ERROR(-20044,'PAYROLL_FROZEN: published payslip cannot change or be deleted.');
   END IF;
   HRMS_ASSERT_PAYROLL_OPEN(:OLD.MAKYCONG);
  END IF;
  IF INSERTING OR UPDATING THEN
   HRMS_ASSERT_PAYROLL_OPEN(:NEW.MAKYCONG);
   IF UPPER(TRIM(:NEW.TRANG_THAI)) IN ('PUBLISHED','APPROVED','CONG_BO','DA_DUYET','PAID','DA_CHI_TRA') THEN
    frozen_periods(:NEW.MAKYCONG):=TRUE;
   END IF;
  END IF;
 END BEFORE EACH ROW;
 AFTER STATEMENT IS
  p PLS_INTEGER;
 BEGIN
  -- Latch only after every row of the publication statement was updated.
  -- A later error rolls the entire statement/transaction back, including this latch.
  p:=frozen_periods.FIRST;
  WHILE p IS NOT NULL LOOP
   UPDATE TB_KYCONG SET LUONG_CONGBO_LOCKED=1,KHOA=1 WHERE MAKYCONG=p AND LUONG_CONGBO_LOCKED=0;
   p:=frozen_periods.NEXT(p);
  END LOOP;
 END AFTER STATEMENT;
END;
/

