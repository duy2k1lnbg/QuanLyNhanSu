SET DEFINE OFF;
WHENEVER SQLERROR CONTINUE;

-- 1. Bổ sung cột EMPLOYEE_CODE vào TB_NHANVIEN nếu chưa có
DECLARE
    v_col_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_col_count 
    FROM user_tab_cols 
    WHERE table_name = 'TB_NHANVIEN' AND column_name = 'EMPLOYEE_CODE';
    
    IF v_col_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TB_NHANVIEN ADD (EMPLOYEE_CODE NVARCHAR2(50))';
    END IF;
END;
/

-- Cập nhật mã mặc định cho nhân viên chưa có mã nghiệp vụ riêng (bảo toàn nguyên vẹn MANV)
UPDATE TB_NHANVIEN 
SET EMPLOYEE_CODE = 'NV' || LPAD(TO_CHAR(MANV), 6, '0') 
WHERE EMPLOYEE_CODE IS NULL;
COMMIT;

-- Thêm unique index cho EMPLOYEE_CODE (chỉ áp dụng cho giá trị NOT NULL)
DECLARE
    v_idx_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_idx_count 
    FROM user_indexes 
    WHERE index_name = 'UQ_NHANVIEN_EMPCODE';
    
    IF v_idx_count = 0 THEN
        BEGIN
            EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UQ_NHANVIEN_EMPCODE ON TB_NHANVIEN(CASE WHEN EMPLOYEE_CODE IS NOT NULL THEN EMPLOYEE_CODE END)';
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END IF;
END;
/

-- 2. Tạo bảng Mapping 1-1 giữa User và Employee: TB_USER_EMPLOYEE_MAPPING
DECLARE
    v_tbl_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_tbl_count 
    FROM user_tables 
    WHERE table_name = 'TB_USER_EMPLOYEE_MAPPING';
    
    IF v_tbl_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE TB_USER_EMPLOYEE_MAPPING (
                ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                USER_ID NUMBER NOT NULL,
                EMPLOYEE_ID NUMBER NOT NULL,
                IS_MOBILE_ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
                CREATED_AT DATE DEFAULT SYSDATE,
                UPDATED_AT DATE,
                CONSTRAINT PK_USER_EMPLOYEE_MAPPING PRIMARY KEY (ID),
                CONSTRAINT UQ_MAPPING_USER UNIQUE (USER_ID),
                CONSTRAINT UQ_MAPPING_EMPLOYEE UNIQUE (EMPLOYEE_ID),
                CONSTRAINT FK_MAPPING_USER FOREIGN KEY (USER_ID) REFERENCES TB_SYS_USER(IDUSER) ON DELETE CASCADE,
                CONSTRAINT FK_MAPPING_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES TB_NHANVIEN(MANV) ON DELETE CASCADE
            )
        ';
    END IF;
END;
/

-- Đồng bộ dữ liệu ban đầu từ TB_SYS_USER.MANV vào TB_USER_EMPLOYEE_MAPPING
MERGE INTO TB_USER_EMPLOYEE_MAPPING m
USING (
    SELECT u.IDUSER AS USER_ID, u.MANV AS EMPLOYEE_ID, 
           CASE WHEN UPPER(TRIM(NVL(u.CLIENT_TYPE, 'ALL'))) = 'DESKTOP' THEN 0 ELSE 1 END AS IS_MOBILE_ENABLED
    FROM TB_SYS_USER u
    WHERE u.MANV IS NOT NULL AND u.MANV > 0
      AND EXISTS (SELECT 1 FROM TB_NHANVIEN nv WHERE nv.MANV = u.MANV)
) src
ON (m.USER_ID = src.USER_ID OR m.EMPLOYEE_ID = src.EMPLOYEE_ID)
WHEN NOT MATCHED THEN
    INSERT (USER_ID, EMPLOYEE_ID, IS_MOBILE_ENABLED, CREATED_AT)
    VALUES (src.USER_ID, src.EMPLOYEE_ID, src.IS_MOBILE_ENABLED, SYSDATE);
COMMIT;

