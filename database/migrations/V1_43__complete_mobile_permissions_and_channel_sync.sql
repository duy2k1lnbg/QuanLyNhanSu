COMMIT;

-- 2. Đồng bộ TB_SYS_RIGHT_CHANNEL cho mọi người dùng
MERGE INTO HR.TB_SYS_RIGHT_CHANNEL tgt
USING (
    SELECT u.IDUSER, 'MOBILE' AS CLIENT_TYPE, f.FUNCTION_CODE,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_VIEW,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_ADD,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_EDIT,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_DELETE,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_PRINT
    FROM HR.TB_SYS_USER u
    CROSS JOIN (
        SELECT 'MOBILE_REQUEST_CORRECTION' AS FUNCTION_CODE FROM DUAL UNION ALL
        SELECT 'MOBILE_PROFILE_EDIT' FROM DUAL UNION ALL
        SELECT 'MOBILE_REQUEST_INSURANCE' FROM DUAL UNION ALL
        SELECT 'MOBILE_REQUEST_DEPENDENT' FROM DUAL
    ) f
) src
ON (tgt.IDUSER = src.IDUSER AND tgt.CLIENT_TYPE = src.CLIENT_TYPE AND tgt.FUNCTION_CODE = src.FUNCTION_CODE)
WHEN MATCHED THEN
    UPDATE SET tgt.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN
    INSERT (IDUSER, CLIENT_TYPE, FUNCTION_CODE, CAN_VIEW, CAN_ADD, CAN_EDIT, CAN_DELETE, CAN_PRINT, CREATED_AT, UPDATED_AT)
    VALUES (src.IDUSER, src.CLIENT_TYPE, src.FUNCTION_CODE, src.CAN_VIEW, src.CAN_ADD, src.CAN_EDIT, src.CAN_DELETE, src.CAN_PRINT, SYSTIMESTAMP, SYSTIMESTAMP);

-- Đảm bảo Quản trị viên (IDUSER = 80) được cấp đầy đủ quyền Mobile
UPDATE HR.TB_SYS_RIGHT_CHANNEL
SET CAN_VIEW = 1, CAN_ADD = 1, CAN_EDIT = 1, CAN_DELETE = 1, CAN_PRINT = 1, UPDATED_AT = SYSTIMESTAMP
WHERE IDUSER = 80 AND CLIENT_TYPE = 'MOBILE'
  AND FUNCTION_CODE IN (
      'MOBILE_ROOT', 'MOBILE_PROFILE_VIEW', 'MOBILE_PROFILE_EDIT',
      'MOBILE_ATTENDANCE_VIEW', 'MOBILE_REQUEST_CORRECTION',
      'MOBILE_PAYROLL_VIEW', 'MOBILE_CONTRACT_VIEW',
      'MOBILE_INSURANCE_VIEW', 'MOBILE_REQUEST_INSURANCE', 'MOBILE_REQUEST_DEPENDENT',
      'MOBILE_NOTIFICATION_VIEW', 'MOBILE_REQUEST_LEAVE',
      'MOBILE_REQUEST_OVERTIME', 'MOBILE_REQUEST_ADVANCE'
  );

-- 3. Đồng bộ TB_SYS_RIGHT (Legacy)
MERGE INTO HR.TB_SYS_RIGHT tgt
USING (
    SELECT u.IDUSER, f.FUNCTION_CODE,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS USER_RIGHT,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_VIEW,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_ADD,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_EDIT,
           CASE WHEN u.IDUSER = 80 THEN 1 ELSE 0 END AS CAN_DELETE
    FROM HR.TB_SYS_USER u
    CROSS JOIN (
        SELECT 'MOBILE_REQUEST_CORRECTION' AS FUNCTION_CODE FROM DUAL UNION ALL
        SELECT 'MOBILE_PROFILE_EDIT' FROM DUAL UNION ALL
        SELECT 'MOBILE_REQUEST_INSURANCE' FROM DUAL UNION ALL
        SELECT 'MOBILE_REQUEST_DEPENDENT' FROM DUAL
    ) f
) src
ON (tgt.IDUSER = src.IDUSER AND tgt.FUNCTION_CODE = src.FUNCTION_CODE)
WHEN MATCHED THEN
    UPDATE SET tgt.CAN_VIEW = tgt.CAN_VIEW
WHEN NOT MATCHED THEN
    INSERT (IDUSER, FUNCTION_CODE, USER_RIGHT, CAN_VIEW, CAN_ADD, CAN_EDIT, CAN_DELETE)
    VALUES (src.IDUSER, src.FUNCTION_CODE, src.USER_RIGHT, src.CAN_VIEW, src.CAN_ADD, src.CAN_EDIT, src.CAN_DELETE);

UPDATE HR.TB_SYS_RIGHT
SET USER_RIGHT = 1, CAN_VIEW = 1, CAN_ADD = 1, CAN_EDIT = 1, CAN_DELETE = 1
WHERE IDUSER = 80
  AND FUNCTION_CODE IN (
      'MOBILE_ROOT', 'MOBILE_PROFILE_VIEW', 'MOBILE_PROFILE_EDIT',
      'MOBILE_ATTENDANCE_VIEW', 'MOBILE_REQUEST_CORRECTION',
      'MOBILE_PAYROLL_VIEW', 'MOBILE_CONTRACT_VIEW',
      'MOBILE_INSURANCE_VIEW', 'MOBILE_REQUEST_INSURANCE', 'MOBILE_REQUEST_DEPENDENT',
      'MOBILE_NOTIFICATION_VIEW', 'MOBILE_REQUEST_LEAVE',
      'MOBILE_REQUEST_OVERTIME', 'MOBILE_REQUEST_ADVANCE'
  );

COMMIT;
