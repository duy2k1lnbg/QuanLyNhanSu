SET DEFINE OFF;
WHENEVER SQLERROR EXIT FAILURE ROLLBACK;
ALTER SESSION SET DDL_LOCK_TIMEOUT=15;

-- 0. Kiểm tra kết nối schema HR
BEGIN
    IF USER <> 'HR' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'HR' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Run V1_43 connected as HR with current schema HR.');
    END IF;
END;
/

-- 1. Bổ sung / chuẩn hóa TB_SYS_FUNCTION
MERGE INTO HR.TB_SYS_FUNCTION tgt
USING (
    SELECT TO_NCHAR('MOBILE_REQUEST_CORRECTION') AS FUNCTION_CODE,
           192 AS SORT,
           TO_NCHAR('Gửi Yêu Cầu Điều Chỉnh Công Mobile') AS DESCRIPTION,
           0 AS ISGROUP,
           TO_NCHAR('MOBILE_ROOT') AS PARENT,
           1 AS MENU,
           TO_NCHAR('Gửi yêu cầu điều chỉnh ngày công, giờ vào ra từ Mobile') AS TIPS,
           'FUNCTION' AS RIGHT_TYPE
    FROM DUAL
) src
ON (tgt.FUNCTION_CODE = src.FUNCTION_CODE)
WHEN MATCHED THEN
    UPDATE SET tgt.PARENT = src.PARENT, tgt.SORT = src.SORT, tgt.DESCRIPTION = src.DESCRIPTION, tgt.RIGHT_TYPE = src.RIGHT_TYPE
WHEN NOT MATCHED THEN
    INSERT (FUNCTION_CODE, SORT, DESCRIPTION, ISGROUP, PARENT, MENU, TIPS, RIGHT_TYPE)
    VALUES (src.FUNCTION_CODE, src.SORT, src.DESCRIPTION, src.ISGROUP, src.PARENT, src.MENU, src.TIPS, src.RIGHT_TYPE);

-- Cập nhật PARENT và tên tiếng Việt chuẩn hóa cho các chức năng Mobile còn thiếu PARENT
UPDATE HR.TB_SYS_FUNCTION
SET PARENT = TO_NCHAR('MOBILE_ROOT')
WHERE FUNCTION_CODE IN ('MOBILE_PROFILE_EDIT', 'MOBILE_REQUEST_INSURANCE', 'MOBILE_REQUEST_DEPENDENT');

UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Đề Xuất / Cập Nhật Hồ Sơ Cá Nhân Mobile') WHERE FUNCTION_CODE = 'MOBILE_PROFILE_EDIT';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Đề Xuất Thay Đổi Bảo Hiểm Mobile') WHERE FUNCTION_CODE = 'MOBILE_REQUEST_INSURANCE';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Đề Xuất Người Phụ Thuộc Mobile') WHERE FUNCTION_CODE = 'MOBILE_REQUEST_DEPENDENT';

-- Chuẩn hóa tên các mã chức năng Mobile khác để tránh mojibake
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Bảng Công Mobile') WHERE FUNCTION_CODE = 'MOBILE_ATTENDANCE_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Hợp Đồng Lao Động Mobile') WHERE FUNCTION_CODE = 'MOBILE_CONTRACT_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Bảo Hiểm Xã Hội Mobile') WHERE FUNCTION_CODE = 'MOBILE_INSURANCE_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Thông Báo Nội Bộ Mobile') WHERE FUNCTION_CODE = 'MOBILE_NOTIFICATION_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Bảng Lương Mobile') WHERE FUNCTION_CODE = 'MOBILE_PAYROLL_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Xem Hồ Sơ Cá Nhân Mobile') WHERE FUNCTION_CODE = 'MOBILE_PROFILE_VIEW';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Phân Hệ Mobile App') WHERE FUNCTION_CODE = 'MOBILE_ROOT';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Gửi Đơn Nghỉ Phép Mobile') WHERE FUNCTION_CODE = 'MOBILE_REQUEST_LEAVE';
UPDATE HR.TB_SYS_FUNCTION SET DESCRIPTION = TO_NCHAR('Gửi Đơn Tăng Ca Mobile') WHERE FUNCTION_CODE = 'MOBILE_REQUEST_OVERTIME';
