--   1. Thêm capability mã 'MOBILE_REQUEST_CORRECTION' vào TB_SYS_FUNCTION
--   2. Chuẩn hóa PARENT = 'MOBILE_ROOT' cho các chức năng Mobile (MOBILE_PROFILE_EDIT,
--      MOBILE_REQUEST_INSURANCE, MOBILE_REQUEST_DEPENDENT)
--   3. Đồng bộ dữ liệu phân quyền TB_SYS_RIGHT_CHANNEL cho tất cả người dùng và nhóm
