WHENEVER SQLERROR EXIT FAILURE ROLLBACK
-- Run as HR. No new user/group scope grants are created.
-- The matching compiled capability also requires F_DM_NHANVIEN.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM HR.TB_SYS_FUNCTION WHERE FUNCTION_CODE='F_DM_NHANVIEN';
    IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20071,'Employee-profile function is unavailable'); END IF;
    SELECT COUNT(*) INTO v_count FROM USER_OBJECTS WHERE OBJECT_NAME='V_AI_SRC_BAOHIEM' AND OBJECT_TYPE='VIEW' AND STATUS='VALID';
    IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20072,'Insurance source is unavailable'); END IF;
    UPDATE AI_OWNER.TB_AI_CAPABILITY
    SET IS_ENABLED=1, REQUIRED_FUNCTION_CODE='F_DM_NHANVIEN'
    WHERE CAPABILITY_CODE='INSURANCE_VIEW' AND SOURCE_VIEW='V_AI_INSURANCE';
    IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20073,'Insurance capability contract mismatch'); END IF;

    FOR c IN (SELECT 'INSURANCE_SELF' code FROM DUAL UNION ALL SELECT 'INSURANCE_VIEW' FROM DUAL) LOOP
        FOR f IN (
            SELECT 'MANV' field FROM DUAL UNION ALL SELECT 'HOTEN' FROM DUAL UNION ALL SELECT 'IDBH' FROM DUAL
            UNION ALL SELECT 'SOBH' FROM DUAL UNION ALL SELECT 'NGAYCAP' FROM DUAL UNION ALL SELECT 'NOICAP' FROM DUAL
            UNION ALL SELECT 'NOIKHAMBENH' FROM DUAL UNION ALL SELECT 'IDPB' FROM DUAL
            UNION ALL SELECT 'TEN_PHONGBAN' FROM DUAL UNION ALL SELECT 'MACTY' FROM DUAL
        ) LOOP
            MERGE INTO AI_OWNER.TB_AI_FIELD_POLICY t
            USING (SELECT c.code cap,f.field logical_field FROM DUAL) s
            ON (t.CAPABILITY_CODE=s.cap AND t.LOGICAL_FIELD=s.logical_field)
            WHEN NOT MATCHED THEN INSERT (CAPABILITY_CODE,LOGICAL_FIELD,ACCESS_MODE,ALLOWED_OPERATIONS)
            VALUES (s.cap,s.logical_field,
                CASE WHEN s.cap='INSURANCE_VIEW' AND s.logical_field='SOBH' THEN 'MASK' ELSE 'FULL' END,
                CASE WHEN s.cap='INSURANCE_VIEW' AND s.logical_field='SOBH' THEN 'LOOKUP,VIEW,LIST,SELF,SELECT' ELSE 'LOOKUP,VIEW,LIST,SELF,SELECT,FILTER,ORDER_BY,GROUP_BY' END);
        END LOOP;
    END LOOP;
    UPDATE AI_OWNER.TB_AI_CAPABILITY SET IS_ENABLED=1, SOURCE_VIEW='hrms_knowledge_active' WHERE CAPABILITY_CODE='POLICY_LOOKUP';
    IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20074,'Policy lookup capability missing'); END IF;
    UPDATE AI_OWNER.TB_AI_REVISION SET REVISION_NUMBER=REVISION_NUMBER+1,UPDATED_AT=CURRENT_TIMESTAMP WHERE REVISION_KEY='POLICY_GLOBAL';
    IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20075,'Policy revision missing'); END IF;
END;

/
COMMIT;
