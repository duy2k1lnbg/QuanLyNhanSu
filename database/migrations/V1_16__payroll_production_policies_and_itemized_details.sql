-- ------------------------------------------------------------------------------
DECLARE
    v_partial_count NUMBER := 0;
    v_history_count NUMBER := 0;
    v_check NUMBER := 0;
    v_schema_ver_cnt NUMBER := 0;
BEGIN
    -- 0.1. Đảm bảo bảng SCHEMA_VERSION tồn tại để theo dõi lịch sử migration
    SELECT COUNT(*) INTO v_schema_ver_cnt FROM USER_TABLES WHERE TABLE_NAME = 'SCHEMA_VERSION';
    IF v_schema_ver_cnt = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE SCHEMA_VERSION (
            INSTALLED_RANK NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            VERSION VARCHAR2(50),
            DESCRIPTION VARCHAR2(200) NOT NULL,
            TYPE VARCHAR2(20) DEFAULT ''SQL'',
            SCRIPT VARCHAR2(1000) NOT NULL,
            CHECKSUM VARCHAR2(100),
            INSTALLED_BY VARCHAR2(100) DEFAULT USER,
            INSTALLED_ON TIMESTAMP DEFAULT SYSTIMESTAMP,
            EXECUTION_TIME_MS NUMBER DEFAULT 0,
            SUCCESS NUMBER(1) DEFAULT 1,
            CONSTRAINT PK_SCHEMA_VERSION PRIMARY KEY (INSTALLED_RANK)
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_SCHEMA_VERSION ON SCHEMA_VERSION (VERSION)';
    END IF;

    -- 0.2. Kiểm tra nếu V1_16 đã được áp dụng thành công trước đó
    IF v_schema_ver_cnt > 0 THEN
        BEGIN
            EXECUTE IMMEDIATE '
                SELECT COUNT(*)
                FROM SCHEMA_VERSION
                WHERE (VERSION = ''1.16'' OR SCRIPT = ''V1_16__payroll_production_policies_and_itemized_details.sql'')
                  AND SUCCESS = 1' INTO v_history_count;
        EXCEPTION WHEN OTHERS THEN
            v_history_count := 0;
        END;
    END IF;

    IF v_history_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'MIGRATION GUARD: V1_16 ALREADY INSTALLED in SCHEMA_VERSION. Migration halted; do not rerun.');
    END IF;

    -- 0.3. Kiểm tra số lượng bảng thuộc V1_16 đã tồn tại trong schema (Migration State)
    SELECT COUNT(*) INTO v_partial_count
    FROM USER_TABLES
    WHERE TABLE_NAME IN (
        'TB_PAYROLL_CALCULATION_RUN',
        'TB_CHINH_SACH_LUONG',
        'TB_CHINH_SACH_BHXH',
        'TB_CHINH_SACH_BHXH_VUNG',
        'TB_CHINH_SACH_CONG_DOAN',
        'TB_THUE_TNCN_CHINH_SACH',
        'TB_THUE_TNCN_BAC',
        'TB_NHANVIEN_BAOHIEM_THAM_GIA',
        'TB_NHANVIEN_CONG_DOAN_THAM_GIA',
        'TB_NHANVIEN_THUE',
        'TB_NGUOI_PHU_THUOC',
        'TB_BANGLUONG_OT_COMPLIANCE',
        'TB_BANGLUONG_CT',
        'TB_BANGLUONG_CT_SOURCE',
        'TB_BANGLUONG_BAOHIEM',
        'TB_BANGLUONG_CONG_DOAN',
        'TB_BANGLUONG_THUE_CT',
        'TB_QUYET_TOAN_THUE_NAM',
        'TB_QUYET_TOAN_THUE_NAM_CT'
    );

    IF v_partial_count > 0 THEN
        IF v_partial_count < 19 THEN
            RAISE_APPLICATION_ERROR(-20000, 'PREFLIGHT: Partial V1_16 migration detected (' || v_partial_count || '/19 tables exist). Repair required; migration halted.');
        ELSE
            RAISE_APPLICATION_ERROR(-20004, 'PREFLIGHT: V1_16 ALREADY INSTALLED (19/19 tables exist). Migration halted; do not rerun.');
        END IF;
    END IF;

    -- 0.4. Xác nhận record IDBL = 1934 (MANV = 2453, MAKYCONG = 202601) tồn tại làm fixture bảo toàn
    SELECT COUNT(*) INTO v_check
    FROM TB_BANGLUONG
    WHERE IDBL = 1934 AND MANV = 2453 AND MAKYCONG = 202601;

    IF v_check = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'PREFLIGHT: Baseline fixture IDBL=1934 (MANV=2453, MAKYCONG=202601) does not exist.');
    END IF;

    -- 0.5. Xác nhận TB_PHUCAP có đủ 13 dòng danh mục gốc
    SELECT COUNT(*) INTO v_check FROM TB_PHUCAP;
    IF v_check != 13 THEN
        RAISE_APPLICATION_ERROR(-20002, 'PREFLIGHT: TB_PHUCAP row count (' || v_check || ') differs from expected enterprise master count (13).');
    END IF;
END;
