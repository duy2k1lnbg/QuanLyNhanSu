-- UTF-8. Add explicit provenance for payroll employee profiles.
-- Existing rows remain UNSPECIFIED; no payroll or employee financial values changed.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
DECLARE n NUMBER; BEGIN
 IF USER<>'HR' THEN RAISE_APPLICATION_ERROR(-20090,'Expected HR schema'); END IF;
 FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME IN ('TB_NHANVIEN_BAOHIEM_THAM_GIA','TB_NHANVIEN_CONG_DOAN_THAM_GIA','TB_NHANVIEN_THUE','TB_NGUOI_PHU_THUOC')) LOOP
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME=t.TABLE_NAME AND COLUMN_NAME='DATA_ORIGIN';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t.TABLE_NAME||' ADD DATA_ORIGIN NVARCHAR2(30) DEFAULT ''UNSPECIFIED'' NOT NULL'; END IF;
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME=t.TABLE_NAME AND COLUMN_NAME='SOURCE_NOTE';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE '||t.TABLE_NAME||' ADD SOURCE_NOTE NVARCHAR2(255)'; END IF;
 END LOOP;
END;
/
INSERT INTO SCHEMA_VERSION(VERSION,DESCRIPTION,TYPE,SCRIPT,INSTALLED_BY,INSTALLED_ON,SUCCESS)
 SELECT '1.38','Payroll profile provenance metadata','SQL','V1_38__payroll_profile_source_metadata.sql',USER,SYSTIMESTAMP,1 FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM SCHEMA_VERSION WHERE VERSION='1.38' AND SUCCESS=1);
COMMIT;
