CREATE OR REPLACE VIEW HR.V_AI_EMPLOYEE_COUNT AS SELECT
 nv.IDPB,TO_CHAR(nv.IDCTY,'TM9') AS MACTY,pb.TENPB AS TEN_PHONGBAN,
 CASE WHEN HR.PKG_AI_READER.FIELD_MODE('TOTAL_COUNT')='FULL' THEN COUNT(*) END AS TOTAL_COUNT
FROM TB_NHANVIEN nv LEFT JOIN TB_PHONGBAN pb ON pb.IDPB=nv.IDPB
WHERE HR.PKG_AI_READER.VIEW_ALLOWED('V_AI_EMPLOYEE_COUNT')=1
 AND HR.PKG_AI_READER.ROW_ALLOWED(nv.MANV,nv.IDPB,TO_CHAR(nv.IDCTY,'TM9'))=1 AND nv.DELETED_DATE IS NULL AND NVL(nv.DATHOIVIEC,0)=0
GROUP BY nv.IDPB,nv.IDCTY,pb.TENPB;
/
