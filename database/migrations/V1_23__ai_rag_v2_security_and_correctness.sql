 nv.MANV,nv.HOTEN,TO_CHAR(nv.IDCTY,'TM9') AS MACTY,nv.IDPB,pb.TENPB AS TEN_PHONGBAN,tc.THANG,tc.NAM,
 CASE WHEN HR.PKG_AI_READER.FIELD_MODE('SOGIO')='FULL' THEN SUM(tc.SOGIO) END AS SOGIO
FROM TB_TANGCA tc JOIN TB_NHANVIEN nv ON nv.MANV=tc.MANV LEFT JOIN TB_PHONGBAN pb ON pb.IDPB=nv.IDPB
WHERE HR.PKG_AI_READER.VIEW_ALLOWED('V_AI_OVERTIME_SUMMARY')=1
 AND HR.PKG_AI_READER.ROW_ALLOWED(nv.MANV,nv.IDPB,TO_CHAR(nv.IDCTY,'TM9'))=1 AND nv.DELETED_DATE IS NULL AND tc.DELETED_DATE IS NULL
