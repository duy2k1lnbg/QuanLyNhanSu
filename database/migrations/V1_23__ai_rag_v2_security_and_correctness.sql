CREATE OR REPLACE PACKAGE HR.PKG_AI_READER AUTHID DEFINER AS
  PROCEDURE BIND_TICKET(p_ticket VARCHAR2,p_self NUMBER DEFAULT 0);
  PROCEDURE CLEAR_REQUEST;
  FUNCTION ROW_ALLOWED(p_manv NUMBER,p_idpb NUMBER,p_company VARCHAR2) RETURN NUMBER;
  FUNCTION VIEW_ALLOWED(p_view VARCHAR2) RETURN NUMBER;
  FUNCTION FIELD_MODE(p_field VARCHAR2) RETURN VARCHAR2;
END;
/
CREATE OR REPLACE PACKAGE BODY HR.PKG_AI_READER AS
  FUNCTION SESSION_KEY RETURN VARCHAR2 IS BEGIN RETURN SYS_CONTEXT('USERENV','SESSIONID')||':'||SYS_CONTEXT('USERENV','INSTANCE'); END;
  PROCEDURE BIND_TICKET(p_ticket VARCHAR2,p_self NUMBER DEFAULT 0) IS
    PRAGMA AUTONOMOUS_TRANSACTION; v_count NUMBER; v_session VARCHAR2(100);
  BEGIN
    v_session := SESSION_KEY;
    DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','TICKET',NULL); DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','SELF_ONLY',NULL);
    IF p_self IS NULL OR p_self NOT IN (0,1) THEN RAISE_APPLICATION_ERROR(-20002,'Invalid scope restriction'); END IF;
    IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'AI_READONLY' THEN RAISE_APPLICATION_ERROR(-20001,'Reader account required'); END IF;
    UPDATE TB_AI_READ_TICKET SET BOUND_SESSION=v_session WHERE TICKET=p_ticket AND BOUND_SESSION IS NULL AND EXPIRES_AT>SYSTIMESTAMP;
    IF SQL%ROWCOUNT != 1 THEN RAISE_APPLICATION_ERROR(-20002,'Invalid or consumed ticket'); END IF;
    COMMIT; DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','TICKET',p_ticket); DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','SELF_ONLY',CASE WHEN p_self=1 THEN '1' ELSE '0' END);
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END;
  PROCEDURE CLEAR_REQUEST IS
    PRAGMA AUTONOMOUS_TRANSACTION; v_ticket VARCHAR2(64); v_session VARCHAR2(100);
  BEGIN
    v_session := SESSION_KEY;
    v_ticket := SYS_CONTEXT('HRMS_AI_CTX','TICKET');
    DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','TICKET',NULL); DBMS_SESSION.SET_CONTEXT('HRMS_AI_CTX','SELF_ONLY',NULL);
    DELETE FROM TB_AI_READ_TICKET WHERE TICKET=v_ticket AND BOUND_SESSION=v_session;
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END;
  FUNCTION VALID_TICKET RETURN TB_AI_READ_TICKET%ROWTYPE IS
    v_ticket TB_AI_READ_TICKET%ROWTYPE; v_count NUMBER; v_session VARCHAR2(100);
  BEGIN
    v_session := SESSION_KEY;
    SELECT t.* INTO v_ticket FROM TB_AI_READ_TICKET t JOIN TB_AI_REVISION r ON r.REVISION_KEY='POLICY_GLOBAL' AND r.REVISION_NUMBER=t.POLICY_REVISION
      JOIN TB_SYS_USER u ON u.IDUSER=t.ACTOR_ID AND NVL(u.DISABLED,0)=0 AND NVL(u.ISGROUP,0)=0
      JOIN TB_AI_CAPABILITY c ON c.CAPABILITY_CODE=t.CAPABILITY_CODE AND c.IS_ENABLED=1
      WHERE t.TICKET=SYS_CONTEXT('HRMS_AI_CTX','TICKET') AND t.BOUND_SESSION=v_session AND t.EXPIRES_AT>SYSTIMESTAMP;
    RETURN v_ticket;
  END;
  FUNCTION HAS_RIGHT(p_actor NUMBER,p_right VARCHAR2) RETURN NUMBER IS v_count NUMBER;
  BEGIN
    IF p_right IS NULL THEN RETURN 1; END IF;
    SELECT COUNT(*) INTO v_count FROM TB_SYS_RIGHT r WHERE r.FUNCTION_CODE=p_right AND (NVL(r.CAN_VIEW,0)=1 OR NVL(r.USER_RIGHT,0)=1)
      AND (r.IDUSER=p_actor OR r.IDUSER IN (SELECT gm.ID_GROUP FROM TB_SYS_GROUP gm JOIN TB_SYS_USER gu ON gu.IDUSER=gm.ID_GROUP WHERE gm.MEMBER=p_actor AND gu.ISGROUP=1 AND NVL(gu.DISABLED,0)=0));
    RETURN CASE WHEN v_count>0 THEN 1 ELSE 0 END;
  END;
  FUNCTION ROW_ALLOWED(p_manv NUMBER,p_idpb NUMBER,p_company VARCHAR2) RETURN NUMBER IS
    t TB_AI_READ_TICKET%ROWTYPE; v_manv NUMBER; v_right VARCHAR2(50); v_allow NUMBER; v_deny NUMBER;
  BEGIN
    t:=VALID_TICKET;
    SELECT MANV INTO v_manv FROM TB_SYS_USER WHERE IDUSER=t.ACTOR_ID;
    SELECT REQUIRED_FUNCTION_CODE INTO v_right FROM TB_AI_CAPABILITY WHERE CAPABILITY_CODE=t.CAPABILITY_CODE;
    IF HAS_RIGHT(t.ACTOR_ID,'F_SYSTEM_AI')=0 OR HAS_RIGHT(t.ACTOR_ID,v_right)=0 THEN RETURN 0; END IF;
    IF (t.CAPABILITY_CODE IN ('PAYROLL_SELF','INSURANCE_SELF') OR SYS_CONTEXT('HRMS_AI_CTX','SELF_ONLY')='1') AND (v_manv IS NULL OR p_manv != v_manv OR p_manv IS NULL) THEN RETURN 0; END IF;
    SELECT NVL(SUM(CASE WHEN EFFECT='ALLOW' THEN 1 ELSE 0 END),0),NVL(SUM(CASE WHEN EFFECT='DENY' THEN 1 ELSE 0 END),0) INTO v_allow,v_deny
      FROM TB_AI_SCOPE_GRANT g WHERE g.CAPABILITY_CODE=t.CAPABILITY_CODE AND g.IS_ENABLED=1
      AND (g.VALID_FROM IS NULL OR g.VALID_FROM<=SYSDATE) AND (g.VALID_TO IS NULL OR g.VALID_TO>SYSDATE)
      AND ((g.SUBJECT_TYPE='USER' AND g.SUBJECT_ID=t.ACTOR_ID) OR (g.SUBJECT_TYPE='GROUP' AND g.SUBJECT_ID IN (SELECT gm.ID_GROUP FROM TB_SYS_GROUP gm JOIN TB_SYS_USER gu ON gu.IDUSER=gm.ID_GROUP WHERE gm.MEMBER=t.ACTOR_ID AND gu.ISGROUP=1 AND NVL(gu.DISABLED,0)=0)))
      AND (g.SCOPE_TYPE='ALL' OR (g.SCOPE_TYPE='SELF' AND p_manv=v_manv) OR (g.SCOPE_TYPE='DEPARTMENT' AND g.SCOPE_KEY=TO_CHAR(p_idpb,'TM9')) OR (g.SCOPE_TYPE='COMPANY' AND g.SCOPE_KEY=p_company));
    RETURN CASE WHEN v_allow>0 AND v_deny=0 THEN 1 ELSE 0 END;
  EXCEPTION WHEN OTHERS THEN RETURN 0;
  END;
  FUNCTION VIEW_ALLOWED(p_view VARCHAR2) RETURN NUMBER IS t TB_AI_READ_TICKET%ROWTYPE; v_view VARCHAR2(100);
  BEGIN
    t:=VALID_TICKET; SELECT SOURCE_VIEW INTO v_view FROM TB_AI_CAPABILITY WHERE CAPABILITY_CODE=t.CAPABILITY_CODE;
    RETURN CASE WHEN p_view=v_view OR p_view IN ('V_AI_ORG_LOOKUP','V_AI_PERIOD') OR (p_view='V_AI_EMPLOYEE_LOOKUP' AND t.CAPABILITY_CODE NOT IN ('EMPLOYEE_COUNT','PAYROLL_SUMMARY')) THEN 1 ELSE 0 END;
  EXCEPTION WHEN OTHERS THEN RETURN 0;
  END;
  FUNCTION FIELD_MODE(p_field VARCHAR2) RETURN VARCHAR2 IS t TB_AI_READ_TICKET%ROWTYPE; v_mode VARCHAR2(20);
  BEGIN
    t:=VALID_TICKET;
    SELECT ACCESS_MODE INTO v_mode FROM TB_AI_FIELD_POLICY WHERE CAPABILITY_CODE=t.CAPABILITY_CODE AND LOGICAL_FIELD=UPPER(p_field);
    RETURN v_mode;
  EXCEPTION WHEN OTHERS THEN RETURN 'DENY';
  END;
END;
