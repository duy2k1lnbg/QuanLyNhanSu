CREATE OR REPLACE PACKAGE BODY HR.PKG_AI_TICKET AS
  PROCEDURE ISSUE(p_actor NUMBER,p_capability VARCHAR2,p_policy_revision NUMBER,p_ticket OUT VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION; v_count NUMBER; v_revision NUMBER;
  BEGIN
    IF SYS_CONTEXT('USERENV','SESSION_USER') <> 'HR' THEN RAISE_APPLICATION_ERROR(-20001,'Trusted application required'); END IF;
    SELECT REVISION_NUMBER INTO v_revision FROM TB_AI_REVISION WHERE REVISION_KEY='POLICY_GLOBAL';
    SELECT COUNT(*) INTO v_count FROM TB_SYS_USER WHERE IDUSER=p_actor AND NVL(DISABLED,0)=0 AND NVL(ISGROUP,0)=0;
    IF v_count != 1 OR v_revision != p_policy_revision THEN RAISE_APPLICATION_ERROR(-20002,'Policy or actor changed'); END IF;
    SELECT COUNT(*) INTO v_count FROM TB_AI_CAPABILITY WHERE CAPABILITY_CODE=p_capability AND IS_ENABLED=1;
    IF v_count != 1 THEN RAISE_APPLICATION_ERROR(-20003,'Capability disabled'); END IF;
    DELETE FROM TB_AI_READ_TICKET WHERE EXPIRES_AT < SYSTIMESTAMP;
    p_ticket := RAWTOHEX(SYS_GUID()) || RAWTOHEX(SYS_GUID());
    INSERT INTO TB_AI_READ_TICKET(TICKET,ACTOR_ID,CAPABILITY_CODE,POLICY_REVISION,EXPIRES_AT)
      VALUES(p_ticket,p_actor,p_capability,p_policy_revision,SYSTIMESTAMP+INTERVAL '40' SECOND);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END;
END;
