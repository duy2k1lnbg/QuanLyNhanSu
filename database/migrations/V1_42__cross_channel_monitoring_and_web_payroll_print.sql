-- Additive metadata. Historical values deliberately remain NULL/unknown.
DECLARE
 PROCEDURE add_col(n VARCHAR2,t VARCHAR2) IS c NUMBER; BEGIN
 SELECT COUNT(*) INTO c FROM USER_TAB_COLUMNS WHERE TABLE_NAME='TB_SYS_LOG' AND COLUMN_NAME=n;
 IF c=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE TB_SYS_LOG ADD ('||n||' '||t||')';END IF; END;
BEGIN
 add_col('CLIENT_TYPE','NVARCHAR2(20)');add_col('DEVICE_ID','NVARCHAR2(100)');add_col('CORRELATION_ID','NVARCHAR2(64)');
 add_col('EVENT_RESULT','NVARCHAR2(20)');add_col('EXECUTOR','NVARCHAR2(30)');add_col('IP_SOURCE','NVARCHAR2(30)');add_col('USER_AGENT','NVARCHAR2(500)');
END;
/
CREATE OR REPLACE TRIGGER HR.TRG_ENFORCE_RIGHT_CHANNEL
BEFORE INSERT OR UPDATE ON HR.TB_SYS_RIGHT_CHANNEL
FOR EACH ROW
BEGIN
    -- Quy tắc 1: Web Portal cấm tuyệt đối action thêm/sửa/xóa đối với Bảng lương
    IF :NEW.CLIENT_TYPE = 'WEB' AND :NEW.FUNCTION_CODE = 'F_CC_BANGLUONG' THEN
        :NEW.CAN_ADD := 0;
        :NEW.CAN_EDIT := 0;
        :NEW.CAN_DELETE := 0;
    END IF;

    -- Quy tắc 2: Mobile App không chấp nhận các chức năng quản trị hệ thống Desktop
    IF :NEW.CLIENT_TYPE = 'MOBILE' AND :NEW.FUNCTION_CODE IN ('F_SYSTEM_DB_CONFIG', 'F_SYSTEM_SAULUU', 'F_SYSTEM_PHUCHOI', 'F_SYSTEM_SETTING') THEN
        :NEW.CAN_VIEW := 0;
        :NEW.CAN_ADD := 0;
        :NEW.CAN_EDIT := 0;
        :NEW.CAN_DELETE := 0;
        :NEW.CAN_PRINT := 0;
    END IF;

    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/


