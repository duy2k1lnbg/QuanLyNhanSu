 SELECT COUNT(*) INTO c FROM USER_INDEXES WHERE INDEX_NAME='IX_SYS_LOG_CORRELATION';
 IF c=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_SYS_LOG_CORRELATION ON TB_SYS_LOG(CORRELATION_ID)'; END IF;
END;
