 align_seq('SEQ_NV_THUE','TB_NHANVIEN_THUE','ID');
 align_seq('SEQ_PAYROLL_CALC_RUN','TB_PAYROLL_CALCULATION_RUN','RUN_ID');
 FOR r IN (SELECT i.table_name,i.column_name,i.generation_type,c.default_on_null
 FROM DBA_TAB_IDENTITY_COLS i JOIN DBA_TAB_COLUMNS c
 ON c.owner=i.owner AND c.table_name=i.table_name AND c.column_name=i.column_name
 WHERE i.owner='HR' AND i.table_name IN ('TB_BANGLUONG_CT_SOURCE','TB_BANGLUONG_CT','TB_BANGLUONG_BAOHIEM','TB_BANGLUONG_CONG_DOAN','TB_BANGLUONG_THUE_CT','TB_BANGLUONG_OT_COMPLIANCE','TB_BANGLUONG','TB_QUYET_TOAN_THUE_NAM_CT','TB_QUYET_TOAN_THUE_NAM','TB_PAYROLL_CALCULATION_RUN','TB_CHAMCONG_BT_LICHSU','TB_CHAMCONG_BATTHUONG','TB_CONG_PD_NGUON','TB_CONG_PHANDOAN','TB_CHAMCONG_KQ_NGAY','TB_CHAMCONG_LANTINH','TB_BANGCONG_CHITIET','TB_KYCONGCHITIET','TB_BANGCONG','TB_KYCONG','TB_YEUCAU_DIEUCHINHCONG','TB_YEUCAU_NGHIPHEP','TB_YEUCAU_TANGCA','TB_TANGCA','TB_HESO_TANGCA','TB_NHANVIEN_PHUCAP','TB_PHUCAP','TB_NGUOI_PHU_THUOC','TB_NHANVIEN_THUE','TB_NHANVIEN_CONG_DOAN_THAM_GIA','TB_NHANVIEN_BAOHIEM_THAM_GIA','TB_BAOHIEM','TB_KHENTHUONG_KYLUAT','TB_UNGLUONG','TB_NHANVIEN_THOIVIEC','TB_DIEUCHUYEN_NHANVIEN','TB_NANGLUONG_NHANVIEN','TB_HOPDONG','TB_LOAIHOPDONG','TB_LICH_LAMVIEC','TB_CA_KHUNGGIO','TB_CA_PHIENBAN','TB_QUYDINH_CHAMCONG','TB_LOAICA','TB_LOAICONG','TB_NGAYLE','TB_NHANVIEN','TB_CONGTY','TB_PHONGBAN','TB_BOPHAN','TB_CHUCVU','TB_CHINH_SACH_BHXH_VUNG','TB_CHINH_SACH_BHXH','TB_CHINH_SACH_LUONG','TB_CHINH_SACH_CONG_DOAN','TB_THUE_TNCN_BAC','TB_THUE_TNCN_CHINH_SACH','TB_UAT_SCENARIO','TB_LUONG_HIEULUC','TB_BAOHIEM_BIENDONG','TB_PHEP_SOPHATSINH','TB_CHAMCONG_SUKIEN','TB_USER_EMPLOYEE_MAPPING')) LOOP
