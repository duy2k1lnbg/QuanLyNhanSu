-- Repair imported explicit keys without resetting sequences backwards.
DECLARE
 n NUMBER; mx NUMBER;
 PROCEDURE align_seq(s VARCHAR2,t VARCHAR2,c VARCHAR2) IS
 BEGIN
  EXECUTE IMMEDIATE 'SELECT NVL(MAX('||c||'),0) FROM HR.'||t INTO mx;
  EXECUTE IMMEDIATE 'SELECT HR.'||s||'.NEXTVAL FROM DUAL' INTO n;
  IF n<=mx THEN
   EXECUTE IMMEDIATE 'ALTER SEQUENCE HR.'||s||' INCREMENT BY '||TO_CHAR(mx+1-n,'FM9999999999999999990');
   EXECUTE IMMEDIATE 'SELECT HR.'||s||'.NEXTVAL FROM DUAL' INTO n;
   EXECUTE IMMEDIATE 'ALTER SEQUENCE HR.'||s||' INCREMENT BY 1';
  END IF;
  DBMS_OUTPUT.PUT_LINE('SEQUENCE_OK '||s);
 END;
BEGIN
 align_seq('SEQ_BANGLUONG_BAOHIEM','TB_BANGLUONG_BAOHIEM','ID');
 align_seq('SEQ_BANGLUONG_CONG_DOAN','TB_BANGLUONG_CONG_DOAN','ID');
 align_seq('SEQ_BANGLUONG_CT','TB_BANGLUONG_CT','IDBLCT');
 align_seq('SEQ_BANGLUONG_CT_SOURCE','TB_BANGLUONG_CT_SOURCE','ID');
