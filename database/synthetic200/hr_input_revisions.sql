CREATE OR REPLACE TRIGGER CC_REV_FRAME AFTER INSERT OR UPDATE OR DELETE ON TB_CA_KHUNGGIO FOR EACH ROW
BEGIN
 FOR d IN (SELECT DISTINCT TRUNC(NGAY,'MM') NGAY FROM TB_LICH_LAMVIEC
    WHERE IDCAPHIENBAN IN (:OLD.IDCAPHIENBAN,:NEW.IDCAPHIENBAN) ORDER BY NGAY) LOOP
  CC_TOUCH_PERIOD(d.NGAY,d.NGAY);
 END LOOP;
END;
