 IF INSERTING OR UPDATING THEN CC_TOUCH_PERIOD(NVL(:NEW.BATDAU_DUYET,:NEW.NGAY),NVL(:NEW.KETTHUC_DUYET,:NEW.NGAY)); END IF;
