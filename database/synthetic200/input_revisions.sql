CREATE OR REPLACE TRIGGER UAT_REV_FRAME AFTER INSERT OR UPDATE OR DELETE ON TB_CA_KHUNGGIO FOR EACH ROW
BEGIN
 UPDATE TB_KYCONG SET CONG_INPUT_REV=NVL(CONG_INPUT_REV,0)+1
 WHERE EXISTS(SELECT 1 FROM TB_LICH_LAMVIEC l WHERE TO_NUMBER(TO_CHAR(l.NGAY,'YYYYMM'))=TB_KYCONG.MAKYCONG
 AND l.IDCAPHIENBAN IN (:OLD.IDCAPHIENBAN,:NEW.IDCAPHIENBAN));
END;
