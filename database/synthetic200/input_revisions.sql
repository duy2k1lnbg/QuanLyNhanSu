CREATE OR REPLACE PROCEDURE UAT_TOUCH_PERIOD(a DATE,b DATE) AS
BEGIN
 UPDATE TB_KYCONG SET CONG_INPUT_REV=NVL(CONG_INPUT_REV,0)+1
 WHERE MAKYCONG BETWEEN TO_NUMBER(TO_CHAR(a,'YYYYMM')) AND TO_NUMBER(TO_CHAR(b,'YYYYMM'));
END;
/
CREATE OR REPLACE TRIGGER UAT_REV_LICH AFTER INSERT OR UPDATE OR DELETE ON TB_LICH_LAMVIEC FOR EACH ROW
BEGIN
 IF UPDATING OR DELETING THEN UAT_TOUCH_PERIOD(:OLD.NGAY,:OLD.NGAY); END IF;
 IF INSERTING OR UPDATING THEN UAT_TOUCH_PERIOD(:NEW.NGAY,:NEW.NGAY); END IF;
END;
/
CREATE OR REPLACE TRIGGER UAT_REV_RAW AFTER INSERT OR UPDATE OR DELETE ON TB_BANGCONG FOR EACH ROW
BEGIN
 IF UPDATING OR DELETING THEN UAT_TOUCH_PERIOD(ADD_MONTHS(DATE '2000-01-01',(:OLD.NAM-2000)*12+:OLD.THANG-1),ADD_MONTHS(DATE '2000-01-01',(:OLD.NAM-2000)*12+:OLD.THANG-1)); END IF;
 IF INSERTING OR UPDATING THEN UAT_TOUCH_PERIOD(ADD_MONTHS(DATE '2000-01-01',(:NEW.NAM-2000)*12+:NEW.THANG-1),ADD_MONTHS(DATE '2000-01-01',(:NEW.NAM-2000)*12+:NEW.THANG-1)); END IF;
END;
/
