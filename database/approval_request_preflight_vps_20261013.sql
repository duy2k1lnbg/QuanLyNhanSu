-- Read-only diagnostics: run as HR or SYS with dictionary access against the VPS database.
-- No NEXTVAL, DML, DDL, passwords, employee contents or JWTs.
SET SERVEROUTPUT ON SIZE UNLIMITED;
SET LINESIZE 220 PAGESIZE 100;
SET VERIFY OFF;
WHENEVER SQLERROR EXIT FAILURE ROLLBACK;
PROMPT DATABASE_TARGET
SELECT SYS_CONTEXT('USERENV','SERVER_HOST') HOST,
       SYS_CONTEXT('USERENV','DB_NAME') DATABASE_NAME,
       SYS_CONTEXT('USERENV','SERVICE_NAME') SERVICE_NAME, USER ACTOR FROM DUAL;
PROMPT REPORTED_CONSTRAINT
SELECT c.OWNER,c.TABLE_NAME,c.CONSTRAINT_NAME,c.CONSTRAINT_TYPE,l.COLUMN_NAME
FROM ALL_CONSTRAINTS c JOIN ALL_CONS_COLUMNS l
 ON l.OWNER=c.OWNER AND l.CONSTRAINT_NAME=c.CONSTRAINT_NAME
WHERE c.OWNER='HR' AND c.CONSTRAINT_NAME='SYS_C0012832'
ORDER BY l.POSITION;
PROMPT AFFECTED_TABLE_PRIMARY_AND_UNIQUE_KEYS
SELECT c.TABLE_NAME,c.CONSTRAINT_NAME,c.CONSTRAINT_TYPE,l.COLUMN_NAME
FROM ALL_CONSTRAINTS c JOIN ALL_CONS_COLUMNS l ON l.CONSTRAINT_NAME=c.CONSTRAINT_NAME AND l.OWNER=c.OWNER
WHERE c.OWNER='HR' AND c.CONSTRAINT_TYPE IN ('P','U') AND c.TABLE_NAME IN
 ('TB_THONGBAO','TB_THONGBAO_NGUOIDUNG','TB_PUSH_OUTBOX',
  'TB_YEUCAU_UNGLUONG','TB_YEUCAU_THAYDOI_HOSO','TB_EMPLOYEE_EDIT_QUOTA',
  'TB_YEUCAU_NGHIPHEP','TB_YEUCAU_DIEUCHINHCONG','TB_YEUCAU_TANGCA','TB_PHEP_SOPHATSINH')
ORDER BY c.TABLE_NAME,c.CONSTRAINT_NAME,l.POSITION;
PROMPT IDENTITY_GENERATORS
SELECT TABLE_NAME,COLUMN_NAME,GENERATION_TYPE,SEQUENCE_NAME
FROM ALL_TAB_IDENTITY_COLS
WHERE OWNER='HR' AND TABLE_NAME IN ('TB_THONGBAO','TB_YEUCAU_NGHIPHEP',
 'TB_YEUCAU_DIEUCHINHCONG','TB_YEUCAU_TANGCA','TB_PHEP_SOPHATSINH')
ORDER BY TABLE_NAME;
DECLARE
 PROCEDURE inspect_pair(t VARCHAR2,s VARCHAR2) IS
   max_id NUMBER; last_id NUMBER; inc NUMBER; caching NUMBER; cyc VARCHAR2(1);
 BEGIN
   EXECUTE IMMEDIATE 'SELECT NVL(MAX(ID),0) FROM HR.'||DBMS_ASSERT.SIMPLE_SQL_NAME(t) INTO max_id;
   SELECT LAST_NUMBER,INCREMENT_BY,CACHE_SIZE,CYCLE_FLAG INTO last_id,inc,caching,cyc
     FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='HR' AND SEQUENCE_NAME=s;
   DBMS_OUTPUT.PUT_LINE(t||' / '||s||': max_id='||max_id||'; sequence_last_number='||last_id||
    '; increment='||inc||'; cache='||caching||'; cycle='||cyc||
    CASE WHEN caching=0 AND last_id<=max_id THEN '; DRIFT_CONFIRMED'
         WHEN caching>0 THEN '; CACHED_SEQUENCE_REQUIRES_MAINTENANCE_CHECK'
         ELSE '; NO_DRIFT_IN_METADATA' END);
 EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE(t||' / '||s||': SEQUENCE_MISSING');
 END;
BEGIN
 IF USER NOT IN ('HR','SYS') THEN RAISE_APPLICATION_ERROR(-20081,'Run in the HR schema on the intended VPS database.'); END IF;
 inspect_pair('TB_THONGBAO','SEQ_THONGBAO');
 inspect_pair('TB_THONGBAO_NGUOIDUNG','SEQ_THONGBAO_NGUOIDUNG');
 inspect_pair('TB_PUSH_OUTBOX','SEQ_PUSH_OUTBOX');
 inspect_pair('TB_YEUCAU_UNGLUONG','SEQ_YEUCAU_UNGLUONG');
 inspect_pair('TB_YEUCAU_THAYDOI_HOSO','SEQ_YEUCAU_THAYDOI_HOSO');
 inspect_pair('TB_EMPLOYEE_EDIT_QUOTA','SEQ_EMPLOYEE_EDIT_QUOTA');
END;
/
PROMPT DIAGNOSTICS_COMPLETE_NO_DATA_CHANGED

